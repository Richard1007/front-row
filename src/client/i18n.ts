function translateReasonPart(value: string): string | undefined {
  const translateKnownValue = (text: string) =>
    ({ 普通话: "Mandarin", 英语: "English", 粤语: "Cantonese" })[text] ?? text;
  let match = value.match(/^(.+) 是你明确选择的艺人$/);
  if (match) return `${match[1]} is an artist you explicitly selected`;
  match = value.match(/^与 (.+) 风格相近$/);
  if (match) return `Similar in style to ${match[1]}`;
  match = value.match(/^符合你对 (.+) 的偏好$/);
  if (match) return `Matches your preference for ${translateKnownValue(match[1]!)}`;
  match = value.match(/^根据所选艺人推断你可能喜欢 (.+)$/);
  if (match) return `Artist profile suggests you may like ${translateKnownValue(match[1]!)}`;
  match = value.match(/^演唱语言包含 (.+)$/);
  if (match) return `Includes ${translateKnownValue(match[1]!)} as a performance language`;
  return exactServerTranslations.get(value);
}

export function translateServerText(locale: Locale, value: string): string {
  if (locale === "zh" || !value) return value;
  const translatedParts = value
    .split("；")
    .map((part) => translateReasonPart(part.trim()))
    .filter((part): part is string => Boolean(part));
  if (translatedParts.length > 0 && translatedParts.length === value.split("；").length) {
    return translatedParts.join("; ");
  }
  const exact = exactServerTranslations.get(value);
  if (exact) return exact;
  const requestFailure = value.match(/^请求失败（(\d+)）$/);
  if (requestFailure) return `Request failed (${requestFailure[1]}).`;
  if (/\p{Script=Han}/u.test(value)) return "The data source returned an untranslated message.";
  return value;
}
