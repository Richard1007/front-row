const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, zh };

export function tr(
  locale: Locale,
  key: TranslationKey,
  variables: Record<string, string | number> = {}
): string {
  return Object.entries(variables).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    dictionaries[locale][key]
  );
}

export function readStoredLocale(storage?: Pick<Storage, "getItem">): Locale {
  try {
    const value = storage?.getItem(LOCALE_STORAGE_KEY);
    return value === "zh" ? "zh" : "en";
  } catch {
    return "en";
  }
}

export function storeLocale(locale: Locale, storage?: Pick<Storage, "setItem">): void {
  try {
    storage?.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // A blocked localStorage should not prevent switching languages for this session.
  }
}

